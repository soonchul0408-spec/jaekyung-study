const ignored = new Set(['옳은 것', '옳지 않은 것', '다음 중', '해당', '기준', '계산', '문제'])

function normalise(value) {
  return String(value || '').replace(/\s+/g, ' ').trim()
}

function usableExpression(value) {
  const text = normalise(value)
  if (!text || text.length < 2 || text.length > 24 || ignored.has(text) || /\d|[=÷+×/]/.test(text) || !/[가-힣]/.test(text)) return null
  return text
}

export function conceptTagsFor(question) {
  const sourceText = [question.stem, ...(question.options || []), question.explanation, ...(question.evidence || []).map((item) => item.text), ...(question.direction?.keyTerms || [])].join(' ')
  const tags = new Map()
  const add = (label, source) => { if (label && !tags.has(label)) tags.set(label, { label, source }) }

  add(normalise(question.concept), '분류')
  for (const [subject, label, aliases] of rules) {
    if (subject === question.subjectId && aliases.some((alias) => sourceText.includes(alias))) add(label, '용어 사전')
  }
  for (const expression of [...(question.direction?.keyTerms || []), ...(question.evidence || []).map((item) => item.text)]) {
    const label = usableExpression(expression)
    if (label) add(label, '문항 표현')
  }
  for (const related of question.relatedConcepts || []) add(usableExpression(related), '연결 개념')

  // 지문에 세부 용어가 없더라도 모든 문항이 학습 지도의 출발점을 갖게 한다.
  if (tags.size === 1) add(question.calculation ? '계산 적용' : '개념 판단', '문항 유형')
  return [...tags.values()]
}

export function applyConceptTags(question) {
  return { ...question, conceptTags: conceptTagsFor(question) }
}
